import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { analyzeScene } from './scene-semantics.mjs'

const baskets = JSON.parse(readFileSync('data/art/scene-baskets.json', 'utf8'))
const places = JSON.parse(readFileSync('data/art/room-prompts-priority.json', 'utf8'))
const placeOf = JSON.parse(readFileSync('data/art/room-place-map.json', 'utf8')).placeOf
const curated = JSON.parse(readFileSync('data/art/room-art-curation.json', 'utf8'))
const protectedPlaces = new Set([
  ...Object.keys(curated.publishedOverrides ?? {}),
  ...(baskets.landmarkPlaces ?? []),
])

const roomsByPlace = new Map()
for (const [roomKey, placeKey] of Object.entries(placeOf)) {
  const split = roomKey.lastIndexOf('-')
  const room = Number(roomKey.slice(split + 1))
  const zone = roomKey.slice(0, split)
  if (!roomsByPlace.has(placeKey)) roomsByPlace.set(placeKey, { zone, rooms: [] })
  roomsByPlace.get(placeKey).rooms.push(room)
}

const toRanges = (rooms) => {
  const sorted = [...rooms].sort((a, b) => a - b)
  const ranges = []
  let first = sorted[0]
  let last = sorted[0]
  for (const room of sorted.slice(1)) {
    if (room === last + 1) last = room
    else {
      ranges.push([first, last])
      first = last = room
    }
  }
  if (sorted.length) ranges.push([first, last])
  return ranges
}

const rules = []
const coverage = {}
const unresolved = []
const placeNameOf = (placeKey) => placeKey.slice(placeKey.indexOf('::') + 2)
const regionalDistrictOf = (identity, placeKey) => {
  const name = placeNameOf(placeKey)
  return Object.entries(identity?.districts ?? {}).find(([, district]) => district.places?.includes(name))?.[0] ?? null
}
for (const [placeKey, place] of Object.entries(places)) {
  const group = roomsByPlace.get(placeKey)
  if (!group || group.rooms.length < 4) continue
  if (protectedPlaces.has(placeKey)) continue

  const reviewed = baskets.reviewedPlaceAssignments?.[placeKey]
  const analysis = reviewed
    ? {
        category: reviewed.category,
        confidence: 1,
        traits: { environment: 'settlement', subtype: 'reviewed-place', civilization: 'urban', water: 'unknown', elevation: 'unknown', route: false },
        signals: [`reviewed:${reviewed.category}`, `reason:${reviewed.reason}`],
      }
    : analyzeScene(place)
  const category = analysis.category
  if (!category) {
    unresolved.push({ placeKey, zone: group.zone, roomCount: group.rooms.length, ...analysis })
    continue
  }

  const regionalIdentity = category === 'regional-city' ? baskets.regionalIdentity?.[place.zoneName] : null
  const regionalDistrict = category === 'regional-city' ? regionalDistrictOf(regionalIdentity, placeKey) : null
  if (place.zoneName === 'Crossing' && category === 'regional-city' && !regionalIdentity?.approvedGenericPlaces?.includes(placeNameOf(placeKey))) {
    unresolved.push({
      placeKey,
      zone: group.zone,
      roomCount: group.rooms.length,
      ...analysis,
      selectionLayer: 'regional-family',
      regionalIdentity: place.zoneName,
      regionalDistrict,
      reason: regionalDistrict ? 'crossing-district-art-required' : 'crossing-place-review-required',
    })
    continue
  }

  const arts = category === 'regional-city'
    ? baskets.regionalCity[place.zoneName]
    : baskets.generic[category]
  if (!arts?.length) {
    unresolved.push({ placeKey, zone: group.zone, roomCount: group.rooms.length, ...analysis, reason: 'no-approved-basket' })
    continue
  }
  for (const art of arts) {
    const local = `public${art}`
    if (!existsSync(local)) throw new Error(`${placeKey}: missing basket art ${local}`)
  }
  rules.push({
    zone: group.zone,
    ranges: toRanges(group.rooms),
    arts,
    placeKey,
    category,
    selectionLayer: category === 'regional-city' ? 'regional-family' : 'archetype',
    regionalIdentity: category === 'regional-city' ? place.zoneName : null,
    regionalDistrict,
    confidence: analysis.confidence,
    traits: analysis.traits,
    signals: analysis.signals,
  })
  coverage[category] = (coverage[category] ?? 0) + group.rooms.length
}

rules.sort((a, b) => a.zone.localeCompare(b.zone, undefined, { numeric: true }) || a.ranges[0][0] - b.ranges[0][0])
const artPools = []
const artPoolIndex = new Map()
for (const rule of rules) {
  const key = JSON.stringify(rule.arts)
  if (!artPoolIndex.has(key)) {
    artPoolIndex.set(key, artPools.length)
    artPools.push(rule.arts)
  }
}
const lines = [
  '// Generated by tools/build-room-scene-patterns.mjs. Edit data/art/scene-baskets.json instead.',
  'type PatternRule = readonly [zone: string, ranges: readonly (readonly [number, number])[], artPool: number]',
  `const HOLD_ROOMS = ${Number(baskets.holdRooms) || 3}`,
  `const ARTS: readonly (readonly string[])[] = ${JSON.stringify(artPools)}`,
  'const RULES: readonly PatternRule[] = [',
]
for (const rule of rules) {
  // Runtime data stays compact; place names, evidence and traits remain in
  // scene-basket-coverage.json where the art-QA report consumes them.
  lines.push(`  ${JSON.stringify([rule.zone, rule.ranges, artPoolIndex.get(JSON.stringify(rule.arts))])},`)
}
lines.push(
  ']',
  '',
  'export function roomScenePattern(zone: string, room: number): string | null {',
  '  for (const rule of RULES) {',
  '    if (rule[0] !== zone) continue',
  '    for (const [first, last] of rule[1]) {',
  '      if (room < first || room > last) continue',
  '      const step = Math.floor((room - first) / HOLD_ROOMS)',
  '      const arts = ARTS[rule[2]]',
  '      return arts[step % arts.length]',
  '    }',
  '  }',
  '  return null',
  '}',
  ''
)
writeFileSync('src/data/roomScenePatterns.ts', lines.join('\n'))

const roomCount = Object.values(coverage).reduce((a, b) => a + b, 0)
const protectedLandmarks = [...protectedPlaces].sort()
const assignments = rules.map(({ placeKey, category, selectionLayer, regionalIdentity, regionalDistrict, zone, ranges, confidence, traits, signals }) => ({
  placeKey,
  category,
  selectionLayer,
  regionalIdentity,
  regionalDistrict,
  zone,
  ranges,
  confidence,
  traits,
  signals,
}))

const regionStats = Object.fromEntries(Object.entries(baskets.auditRegions ?? {}).map(([name, zones]) => {
  const zoneSet = new Set(zones)
  const regionAssignments = assignments.filter((item) => zoneSet.has(item.zone))
  const regionUnresolved = unresolved.filter((item) => zoneSet.has(item.zone))
  return [name, {
    assignedPlaceCount: regionAssignments.length,
    assignedRoomCount: regionAssignments.reduce((sum, item) => sum + item.ranges.reduce((rangeSum, [first, last]) => rangeSum + last - first + 1, 0), 0),
    unresolvedPlaceCount: regionUnresolved.length,
    unresolvedRoomCount: regionUnresolved.reduce((sum, item) => sum + item.roomCount, 0),
  }]
}))

// Keep the repository-facing file small and reviewable. The complete evidence
// set is generated into data/art/out (already ignored by git) and uploaded by
// CI so investigators can inspect every automatic and unresolved decision.
writeFileSync('data/art/scene-basket-coverage.json', JSON.stringify({
  ruleCount: rules.length,
  roomCount,
  assignmentCount: assignments.length,
  unresolvedCount: unresolved.length,
  coverage,
  regions: regionStats,
  protectedLandmarkCount: protectedLandmarks.length,
  protectedLandmarks,
}, null, 2) + '\n')

mkdirSync('data/art/out', { recursive: true })
writeFileSync('data/art/out/scene-basket-audit.json', JSON.stringify({
  ruleCount: rules.length,
  roomCount,
  coverage,
  protectedLandmarks,
  assignments,
  unresolved,
}, null, 2) + '\n')

console.log(`wrote ${rules.length} rules covering ${roomCount} rooms`)
console.log(`${unresolved.length} multi-room places remain intentionally unassigned or lack an approved basket`)
