// Build orchestration only: geometry and engine conversion belong to Scene Forge.
import {readFileSync,writeFileSync,existsSync,mkdtempSync,copyFileSync} from 'node:fs'
import {resolve,join} from 'node:path'
import {tmpdir} from 'node:os'
import {execFileSync} from 'node:child_process'
import {createHash} from 'node:crypto'
const hash=v=>createHash('sha256').update(v).digest('hex')
export function compileCrossingShells(compositions) {
  const definitions={}
  for (const r of compositions) for (const p of r.pieces) if (p.proceduralMesh) definitions[p.proceduralMesh]=p.definition
  const names=Object.keys(definitions).sort()
  if (!names.length) throw new Error('No Rust shell definitions were produced')
  const recipe={version:1,definitions:Object.fromEntries(names.map(n=>[n,definitions[n]])),
    root:{kind:'group',children:names.map(mesh=>({kind:'part',mesh}))}}
  const shared=resolve(process.env.SCENE_FORGE_ROOT??'../shared-catalog')
  const sources=['procedural/Cargo.toml','procedural/Cargo.lock','procedural/src/lib.rs','procedural/src/room.rs','procedural/src/main.rs','procedural/godot/pack_scene.gd','procedural/godot/addons/scene_forge/import_scene.gd']
  const sourceHashes=Object.fromEntries(sources.map(p=>[p,hash(readFileSync(join(shared,p)))]))
  const key=hash(JSON.stringify({recipe,sourceHashes}))
  const output='godot/assets/crossing/procedural-shells.scn'
  const receiptPath='godot/assets/crossing/procedural-shells.json'
  if (existsSync(receiptPath)&&existsSync(output)) {
    const old=JSON.parse(readFileSync(receiptPath,'utf8'))
    if (old.inputHash===key && old.outputHash===hash(readFileSync(output))) return
  }
  if (!process.env.GODOT4) throw new Error('Set GODOT4 to build changed Rust shells; previous package is not silently reused')
  const scratch=mkdtempSync(join(tmpdir(),'crossing-scene-forge-'))
  const input=join(scratch,'recipe.json'), compiled=join(scratch,'scene.json'), packed=join(scratch,'shells.scn')
  writeFileSync(input,JSON.stringify(recipe))
  execFileSync(process.env.CARGO??'cargo',['build','--release','--locked','--manifest-path',join(shared,'procedural/Cargo.toml')],{stdio:'inherit'})
  execFileSync(join(shared,'procedural/target/release/scene-forge-cli'+(process.platform==='win32'?'.exe':'')),[input,compiled],{stdio:'inherit'})
  execFileSync(process.env.GODOT4,['--headless','--path',join(shared,'procedural/godot'),'--script','res://pack_scene.gd','--',compiled,packed],{stdio:'inherit'})
  if (!existsSync(packed)) throw new Error('Scene Forge did not produce its package')
  copyFileSync(packed,output)
  const data=JSON.parse(readFileSync(compiled,'utf8'))
  writeFileSync(receiptPath,JSON.stringify({schemaVersion:1,inputHash:key,sourceHashes,
    sourceRepository:'https://github.com/dancockrell/shared-game-environment-library',
    sourceRevision:execFileSync('git',['-C',shared,'rev-parse','HEAD'],{encoding:'utf8'}).trim(),
    license:'Original procedural geometry; generated by MIT-licensed Scene Forge',
    reviewStatus:'construction-prototype-not-final-art',outputHash:hash(readFileSync(output)),
    meshCount:data.meshes.length,estimatedGeometryBytes:data.estimated_geometry_bytes,
    definitions:names},null,2)+'\n')
  console.log('Packaged '+names.length+' shared Rust room-shell meshes')
}
