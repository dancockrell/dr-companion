/**
 * Generate docs/CROSSING_BUILD_LIST.md - what has to be modelled for zone 1,
 * and the grid that says where each piece goes.
 *
 * Generated rather than hand-written for one reason: every number in it is a
 * count over `data/art/out/geometric-room-briefs.json`, and a hand-maintained
 * doc would start drifting from that file the first time the briefs are
 * rebuilt. The prose is authored here; the figures are derived on every run.
 * Editing the output by hand is therefore pointless - it is overwritten.
 *
 * This is deliberately NOT a second copy of
 * `data/art/out/geometric-room-briefs-crossing.md`, which the same pipeline
 * already emits. That file is a per-place catalogue: one section per room
 * brief, 4,000-odd lines, for looking a room up. This one is a synthesis by
 * asset family plus the placement grid, for deciding what to build next.
 * Different questions, one source.
 *
 *     node tools/build-crossing-build-list.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const ZONE = '1'
const BRIEFS = 'data/art/out/geometric-room-briefs.json'
const OUT = 'docs/CROSSING_BUILD_LIST.md'

/** A 5 m cell at the world manifest's own 0.25 m per map unit. Kept equal to
 * `mapUnitToMetres` in build-primitive-world-manifest.mjs on purpose: two
 * coordinate systems for one town is the drift this pipeline exists to
 * avoid. */
const MAP_UNIT_TO_METRES = 0.25
const CELL_METRES = 5
const CELL_UNITS = CELL_METRES / MAP_UNIT_TO_METRES // 20

const briefs = JSON.parse(readFileSync(BRIEFS, 'utf8'))
const rooms = briefs.roomBriefs.filter((r) => r.zone === ZONE)

// A floor, not a comment. If the briefs are ever rebuilt into a shape this
// script does not understand, an empty or tiny result must stop the run
// rather than quietly publishing a build list describing an empty town.
const MIN_ROOMS = 500
if (rooms.length < MIN_ROOMS) {
  throw new Error(
    `Only ${rooms.length} rooms found for zone ${ZONE}, expected at least ${MIN_ROOMS}. ` +
      `Refusing to write a build list from what looks like truncated or reshaped briefs.`
  )
}

const mapped = rooms.filter((r) => r.map)
const described = rooms.filter((r) => r.briefStatus === 'described')
const undescribed = rooms.filter((r) => r.briefStatus === 'missing-description')

const countTag = (tag) => rooms.filter((r) => r.classification.tags.includes(tag)).length
const countKind = (k) => rooms.filter((r) => r.classification.specialKinds.includes(k)).length
const countMode = (m) => rooms.filter((r) => r.classification.spatialMode === m).length

const placesFor = (pred) =>
  [...new Set(rooms.filter(pred).map((r) => r.placeId.split('::').slice(1).join('::')))].sort()

const xs = mapped.map((r) => r.map.x)
const ys = mapped.map((r) => r.map.y)
const minX = Math.min(...xs)
const maxX = Math.max(...xs)
const minY = Math.min(...ys)
const maxY = Math.max(...ys)
const cols = Math.floor((maxX - minX) / CELL_UNITS) + 1
const rowsN = Math.floor((maxY - minY) / CELL_UNITS) + 1
const levels = [...new Set(mapped.map((r) => r.map.z ?? 0))].sort()

const colLetter = (c) => (c < 26 ? String.fromCharCode(65 + c) : 'A' + String.fromCharCode(65 + c - 26))
const cellFor = (r) => {
  const col = Math.floor((r.map.x - minX) / CELL_UNITS)
  const row = Math.floor((r.map.y - minY) / CELL_UNITS)
  return `${r.map.z ?? 0}/${colLetter(col)}${String(row).padStart(2, '0')}`
}

// A real room, named, so the worked example below cannot be wrong the way a
// hand-typed one can. Picked by id rather than by position so it is stable.
const example = mapped.find((r) => r.id === '1-4') ?? mapped[0]

/** How many distinct 5 m cells actually carry a room. */
const occupied = new Set(mapped.map(cellFor)).size

const list = (names, n) => names.slice(0, n).join(' · ') + (names.length > n ? ` · …and ${names.length - n} more` : '')

const guildPlaces = placesFor((r) => r.classification.specialKinds.includes('guild'))
const landmarkPlaces = placesFor((r) => r.classification.specialKinds.includes('landmark'))
const gatePlaces = placesFor((r) => r.classification.specialKinds.includes('gate'))
const marketPlaces = placesFor((r) => r.classification.specialKinds.includes('market'))
const bankPlaces = placesFor((r) => r.classification.specialKinds.includes('banking'))
const sacredPlaces = placesFor((r) => r.classification.specialKinds.includes('sacred'))
const interiorPlaces = placesFor((r) => r.classification.tags.includes('interior'))

const md = `# The Crossing, room by room

> Generated by \`tools/build-crossing-build-list.mjs\` from \`${BRIEFS}\`.
> Do not edit by hand - re-run the script. Every figure below is counted from
> the briefs at generation time, so it cannot drift from the data.

Everything that has to be modelled to stand up zone ${ZONE}, drawn from the
${described.length} authored room descriptions the map already carries, plus a
grid that says where each piece goes.

| | |
|---|---|
| Rooms | ${rooms.length} |
| With an authored description | ${described.length} |
| No description on file | ${undescribed.length} |
| X range | ${minX} … ${maxX} |
| Y range | ${minY} … ${maxY} |
| Levels | ${levels.join(', ')} |
| Grid | ${cols} × ${rowsN} cells of ${CELL_METRES} m |
| Cells actually occupied | ${occupied} of ${cols * rowsN} |

## 1. Where everything goes

Every room already has a position. The map gives each one an \`x\`, a \`y\` and a
\`z\`, and those are authoritative - they are what the client draws its own map
from and what the world manifest already uses to place cells. Nothing here
needs surveying; it needs bucketing.

A cell is ${CELL_METRES} m square. At the established ${MAP_UNIT_TO_METRES} m
per map unit that is exactly ${CELL_UNITS} map units across, which keeps this
list and the world manifest on one coordinate system rather than two.

\`\`\`
col  = floor((x - (${minX})) / ${CELL_UNITS})    // 0 … ${cols - 1}
row  = floor((y - (${minY})) / ${CELL_UNITS})    // 0 … ${rowsN - 1}
cell = level + "/" + letter(col) + pad(row)

// ${example.title} - room ${example.id}
// x ${example.map.x}, y ${example.map.y}, z ${example.map.z ?? 0}  ->  ${cellFor(example)}
\`\`\`

Columns run \`A\`-\`Z\` then \`AA\`-\`${colLetter(cols - 1)}\`; rows are zero-padded to
two digits. Level comes first because the two levels are different builds -
level 1 is upper floors and battlement walks, and shares no ground with level 0.

Roughly ${Math.round((occupied / (cols * rowsN)) * 100)}% of the grid carries a
room. The gaps are the blocks the streets run between and should stay unbuilt
rather than being filled with invented alleys.

**Filing.** One file per occupied cell, named for the cell, so a builder can
find a piece from a room id and a room id from a piece without a lookup table:
\`cells/0/${cellFor(example).split('/')[1]}.tscn\`. Shared kits live outside the
grid under \`kits/\`, because a bench belongs to the town rather than to one
address.

## 2. What the town is made of

The descriptions are specific and they repeat: stone, timber, whitewash and
marble, with water through the middle of it. It is a river town whose civic
centre puts on marble for the occasion. Build the ordinary streets from shared
parts so the specific places can afford to be built properly - a tavern
described as ramshackle and part-built from the hull of a beached trading
galleon is not a reskin of the building next to it.

## 3. The ground and the streets

**${countMode('exterior-cell')} exterior cells · ${countTag('ordinary')} classified ordinary**

Half the town is outdoors and most of that is street. These rooms describe a
surface, frontages either side, and what can be seen down the road - and the
seeing-down-the-road is the part that matters, because a MUD player's sense of
place comes almost entirely from what a room says is visible from it.

- **Ground plates, ${CELL_METRES} m** - cobble, packed dirt, flagstone, grass
- **Frontage panels** - three widths, four finishes: whitewash, timber, rough stone, dressed stone
- **Corner and junction pieces** - streets meet at right angles nearly everywhere
- **Street furniture** - benches, lamp posts, signboards, barrels, crates, a well
- **Lunat trees and planting** - the Green is defined by its stand of lunat trees; a named species, not generic foliage

## 4. The river, the quays and the bridges

**${countTag('water')} rooms mention water · ${countMode('waterfront')} waterfront · ${countTag('bridge')} bridge · ${countMode('bridge-water')} bridge-over-water**

The Oxenwaithe is why the town is called the Crossing. The descriptions carry
current and sound as much as surface. The bank should read as worked: this is a
commercial river with a barque, a trollferry and a quay, not scenery.

- **Water ribbon, ${CELL_METRES} m** - straight, bend, widening; animated flow rather than a flat plane
- **Bank edges** - dressed stone embankment, timber quay, rough natural bank; three districts, not interchangeable
- **Bridge spans** - span, abutments, rail
- **Ferry and landing** - moored hull and gangway
- **Waterside props** - bollards, coiled rope, crates, nets, a crane at the storage wharf

## 5. The wall, the gates and the battlements

**${countKind('gate')} gate rooms · ${gatePlaces.length} named places**

The town is walled and the wall is walkable - the battlement rooms are why
level 1 exists. Gates are thresholds in the strong sense: where the town stops,
where guards stand, and where the description turns outward to name what lies
beyond.

- **Curtain wall, ${CELL_METRES} m** - plain run, and a run with a stair
- **Battlement walk** - the level-1 counterpart, crenellations and an inside edge
- **Gatehouse** - arch, portcullis, flanking towers, open and closed states
- **Guard post** - brazier, weapon rack, bench

${list(gatePlaces, 14)}

## 6. Interiors

**${countTag('interior')} interior rooms · ${interiorPlaces.length} distinct places**

The largest single body of work. These are not variations on one shop - they
are workrooms, auction halls, cellars, dormitories, an alchemy kitchen, a cigar
lounge, a chamber of justice, a conservatory, an auditorium.

Interiors are cutaways: the viewer looks into a room with its near wall removed,
which is why the spatial mode is \`interior-cutaway\` rather than "building". The
build is a floor, three walls, an omittable ceiling, and furniture - and the
furniture is where the character is.

- **Cutaway shell** - small, medium, hall
- **Surfaces** - plank, flagstone, polished stone, marble, rush-strewn
- **Counters and tables** - shop counter, refectory table, work bench, writing desk
- **Seating** - bench, stool, chair, upholstered
- **Storage** - shelving, barrels, crates, strongbox, wall racks
- **Working equipment** - forge and anvil, alchemy bench, loom, potter's wheel, auction block, lectern
- **Light** - lanterns, sconces, hearth, window shafts

${list(interiorPlaces, 24)}

## 7. The guilds

**${countKind('guild')} guild rooms**

Guilds run to whole suites rather than single rooms. A guild is the one place a
player returns to constantly, so the threshold and the first room inside carry
disproportionate weight - build those before the eleventh back corridor.

- **Guild threshold kit** - door, sign, approach paving, the exterior tell
- **Hall and courtyard shells** - larger than the shop cutaway, often around an open courtyard
- **One guild-specific fixture each** - what stops ${countKind('guild')} rooms reading as one building

${list(guildPlaces, 20)}

## 8. Landmarks

**${countKind('landmark')} landmark rooms · ${landmarkPlaces.length} named places**

These are the silhouettes the town is recognised by, and several are visible
from rooms nowhere near them - the Temple's towers are seen and smelled from
streets away, the Academy blocks the light on Sirenberry Row. Landmarks
therefore exist twice: as the place you stand in, and as a distant silhouette
other cells can see. **Build the far view first** - it appears in far more rooms
than the near one.

- **Distant silhouette set** - Temple towers, Arena dome, Academy mass, Town Hall, Provincial Bank
- **Arena** - curved inscribed wall, dome, stands, the square outside
- **Fountains** - the Central and Crystal fountains are separate landmarks and should not share a model
- **The Carousel** - a complex of its own: square, chamber, booth, desk
- **The Dig** - an excavation; terrain rather than architecture

${list(landmarkPlaces, 18)}

## 9. Market, bank and shrine

**${countKind('market')} market · ${countKind('banking')} banking · ${countKind('sacred')} sacred**

Three small groups each wanting their own vocabulary. The market is canopies and
trestles; the bank is the town's one formal interior; the shrines are mostly
small and outdoors, and one is a rock garden behind a guildhall that you only
recognise as a shrine when you notice the offerings among the stones.

- **Market canopy and trestle** - two or three widths, awning cloth, goods heaps
- **Teller counter and vault door** - marble, polished wood, brass
- **Shrine kit** - altar, offering bowl, brazier, rock-garden arrangement

Market: ${list(marketPlaces, 10)}

Banking: ${list(bankPlaces, 10)}

Sacred: ${list(sacredPlaces, 10)}

## 10. Coverage

| Group | Rooms | Spatial mode |
|---|---:|---|
| Exterior streets and squares | ${countMode('exterior-cell')} | exterior-cell |
| Interiors | ${countMode('interior-cutaway')} | interior-cutaway |
| Waterfront | ${countMode('waterfront')} | waterfront |
| Bridges over water | ${countMode('bridge-water')} | bridge-water |
| No description on file | ${countMode('unresolved')} | unresolved |

### The ${undescribed.length} undescribed are not empty rooms

${undescribed.length} rooms have a title and a map position but no description
in the current data. \`${undescribed[0]?.id}\` (${undescribed[0]?.title}) is one
of them, with ${undescribed[0]?.map?.exits?.length ?? 0} exits - a real and
quite busy street.

Build them as ordinary cells of the right surface and leave them deliberately
plain. A guessed description becomes indistinguishable from an authored one the
moment it is modelled, and there is no way back from that.

### Trust the description over the tag

The classification is a good starting point and it is not perfect. Some rooms
carry a tag the room text does not support - *Town Green South* is tagged
\`interior\` and is plainly an outdoor green with lunat trees and birds.

Where the two disagree the room description is the authority: it is the authored
artefact, and the tags are derived from it. Fixing a tag is cheap; building an
indoor room outdoors is not.

## 11. Suggested order

Ground plates and frontage panels first - they unblock
${countMode('exterior-cell')} cells at once and make the town walkable end to
end. Then the river, which is the town's spine and its name. Then the distant
silhouette set, because it appears in far more rooms than the landmarks
themselves and makes every street look finished from the inside. Then interiors,
starting with the guilds a new character enters in their first hour. The
${undescribed.length} undescribed rooms come last and stay plain.
`

mkdirSync('docs', { recursive: true })
writeFileSync(OUT, md)
console.log(
  `${OUT}: ${rooms.length} rooms, ${described.length} described, ` +
    `${cols}x${rowsN} grid, ${occupied} cells occupied`
)
